"""Recommendation variety check (V2-SR-05): how MMR's λ trades relevance for variety.

    uv run python -m app.recommend_benchmark      # writes docs/recommend_quality.md

For a few typical interest sets (a new user who chose only interests, no feedback, October),
we build the top 10 with different λ values and measure:

- relevance: the average score of the 10 items (higher = closer to the user's taste);
- variety (intra-list diversity, ILD): the average of 1 - similarity(a, b) over every pair of
  items in the list, with the same similarity MMR uses (half cosine of interests + tags, half
  "same kind of item"). 0 = ten copies of one item.
- categories: how many different kinds of item (temple, lake, trek, ...) are in the list.

We want a λ that adds clear variety while losing very little relevance.
"""

import uuid
from itertools import combinations
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models import Interest, User
from app.models.enums import Lang, Nationality
from app.services.recommend import MMR_LAMBDA, _candidates, item_similarity, recommend

OUT = Path(__file__).resolve().parents[2] / "docs" / "recommend_quality.md"
INTEREST_SETS = [
    ("culture", "religious"),
    ("nature", "adventure"),
    ("culture",),
    ("nature",),
    ("adventure",),
    ("religious",),
]
LAMBDAS = [1.0, 0.85, MMR_LAMBDA, 0.6, 0.5]
MONTH, LIMIT = 10, 10


def _kind(rec) -> str:
    return "trek" if rec.type == "trek" else rec.item.category.code


def measure(db: Session, lam: float) -> dict:
    by_id = {c.id: c for c in _candidates(db, Lang.en, MONTH, None, Nationality.foreign)}
    relevance = variety = kinds = 0.0
    lists = {}
    for codes in INTEREST_SETS:
        user = User(id=uuid.uuid4(), email="benchmark@example.com")  # not saved
        user.interests = list(db.scalars(select(Interest).where(Interest.code.in_(codes))))
        out = recommend(db, user, Lang.en, LIMIT, MONTH, mmr_lambda=lam)
        items = out.items
        pairs = list(combinations(items, 2))
        relevance += sum(x.score for x in items) / len(items)
        variety += sum(
            1 - item_similarity(by_id[a.item.id], by_id[b.item.id]) for a, b in pairs
        ) / len(pairs)
        kinds += len({_kind(x) for x in items})
        lists[codes] = [_kind(x) for x in items]
    n = len(INTEREST_SETS)
    return {"relevance": relevance / n, "variety": variety / n, "kinds": kinds / n, "lists": lists}


def report(results: dict[float, dict]) -> str:
    base = results[1.0]
    lines = [
        "# Recommendation variety (MMR)",
        "",
        "*Generated by `cd backend && uv run python -m app.recommend_benchmark` (do not edit by "
        "hand).*",
        "",
        f"Top {LIMIT} for {len(INTEREST_SETS)} new users who only chose interests "
        f"({', '.join(' + '.join(s) for s in INTEREST_SETS)}), month {MONTH}. "
        "λ = 1 is plain sorting by score (no MMR).",
        "",
        "| λ | Relevance (avg score) | Variety (ILD) | Kinds of item in the top 10 |",
        "|---|---|---|---|",
    ]
    for lam, r in results.items():
        mark = " **(used)**" if lam == MMR_LAMBDA else ""
        rel = (r["relevance"] / base["relevance"] - 1) * 100
        var = (r["variety"] / base["variety"] - 1) * 100
        lines.append(
            f"| {lam}{mark} | {r['relevance']:.3f} ({rel:+.1f}%) | {r['variety']:.3f} "
            f"({var:+.0f}%) | {r['kinds']:.1f} |"
        )
    lines += ["", f"Kinds of item in each list at λ = {MMR_LAMBDA}:", ""]
    lines += ["| Interests | Top 10 (in order) |", "|---|---|"]
    for codes, kinds in results[MMR_LAMBDA]["lists"].items():
        lines.append(f"| {' + '.join(codes)} | {', '.join(kinds)} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    from app.core.db import SessionLocal

    with SessionLocal() as db:
        results = {lam: measure(db, lam) for lam in LAMBDAS}
        db.rollback()
    OUT.write_text(report(results), encoding="utf-8")
    for lam, r in results.items():
        print(f"λ {lam}: relevance {r['relevance']:.3f}, variety {r['variety']:.3f}")
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
